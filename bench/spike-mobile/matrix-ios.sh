#!/usr/bin/env bash
# The test page in Safari on the iOS Simulator (macOS; MACMINI.md: serve.mjs running on the same Mac),
# for every candidate engine, two repetitions per configuration. Results:
#   bench/results/<date>-ios-simulador-safari<version>-<engine>-<variant>-<model>[<SUFFIX>]-r<k>.json
# Usage: bash bench/spike-mobile/matrix-ios.sh [repetition numbers, default "1 2"] [configs...]
# A config is "engine variant model"; without configs, the list below runs. EXTRA adds query
# parameters and SUFFIX tags the file name (e.g. EXTRA="&warm=0&endurance=200" SUFFIX=-resistencia-200).
# run-ios.mjs erases the dedicated simulator before every run. Written for the bash 3.2 of macOS.
# Do not edit this file while it runs: bash reads scripts as it executes them.
HERE="$(cd "$(dirname "$0")" && pwd)"
DATE="$(date +%F)"
REPS="${1:-1 2}"
if [ $# -gt 0 ]; then shift; fi
if [ $# -gt 0 ]; then
  CONFIGS=("$@")
else
  CONFIGS=(
    "ort-wasm int8 ts-ettin-17m" "ort-wasm 8bit ts-ettin-17m" "ort-wasm fp32 ts-ettin-17m" "ort-wasm q8emb-f16 ts-ettin-17m"
    "jh-cpu f32 ts-ettin-17m"
    "ort-wasm int8 ts-ettin-32m" "ort-wasm 8bit ts-ettin-32m" "jh-cpu f32 ts-ettin-32m"
    "ort-webgpu 8bit ts-ettin-17m" "jh-webgpu f32 ts-ettin-17m"
  )
fi
RUNTIME_ROOT="$(xcrun simctl list runtimes -j | python3 -c 'import json,sys; r=[x for x in json.load(sys.stdin)["runtimes"] if "iOS" in x["identifier"]]; print(sorted(r, key=lambda x: [int(p) for p in x["version"].split(".")])[-1]["runtimeRoot"])')"
SAFARI="$(plutil -extract CFBundleShortVersionString raw "$RUNTIME_ROOT/Applications/MobileSafari.app/Info.plist" | cut -d. -f1)"
for k in $REPS; do
  for config in "${CONFIGS[@]}"; do
    set -- $config
    name="$DATE-ios-simulador-safari$SAFARI-$1-$2-$3${SUFFIX:-}-r$k"
    node "$HERE/run-ios.mjs" --result "$name" --timeout 1200 \
      --path "/index.html?engine=$1&variant=$2&model=$3${EXTRA:-}&name=$name" | tail -1
  done
done
