#!/usr/bin/env bash
# T-08 — the test page in Chrome on the Android emulator, for every candidate engine, two repetitions
# per configuration (EMULADOR.md: emulator up, serve.mjs running). Results:
#   bench/results/<date>-emulador-chrome<version>-<engine>-<variant>-<model>-r<k>.json
# Usage: bash bench/spike-mobile/matrix-emulador.sh [repetition numbers, default "1 2"] [configs...]
# A config is "engine variant model"; without configs, the T-08 list below runs.
# EXTRA adds query parameters and SUFFIX tags the file name, e.g. the T-09 endurance runs:
#   EXTRA="&warm=0&endurance=200" SUFFIX=-resistencia-200 bash matrix-emulador.sh "1" "ort-wasm 8bit ts-ettin-17m"
# FLAGS passes Chrome command-line flags, e.g. FLAGS=--enable-precise-memory-info (exact performance.memory).
# RESTART=1 cold-boots the emulator (android-agent-skill) before every run. Not needed since
# run-android.mjs clears Chrome's data before each run (restored tabs had piled up and frozen it).
# Do not edit this file while it runs: bash reads scripts as it executes them.
set -u
# Git Bash: native path for node (pwd -W), and no path conversion for the device paths adb receives.
HERE="$(cd "$(dirname "$0")" && (pwd -W 2>/dev/null || pwd))"
export MSYS_NO_PATHCONV=1
DATE="$(date +%F)"
REPS="${1:-1 2}"; shift || true
CONFIGS=("$@")
if [ ${#CONFIGS[@]} -eq 0 ]; then
  CONFIGS=(
    "ort-wasm int8 ts-ettin-17m" "ort-wasm 8bit ts-ettin-17m" "ort-wasm fp32 ts-ettin-17m" "ort-wasm q8emb-f16 ts-ettin-17m"
    "jh-cpu f32 ts-ettin-17m"
    "ort-wasm int8 ts-ettin-32m" "ort-wasm 8bit ts-ettin-32m" "jh-cpu f32 ts-ettin-32m"
    "ort-webgpu 8bit ts-ettin-17m" "jh-webgpu f32 ts-ettin-17m"
  )
fi
ADB="${ANDROID_HOME:-$LOCALAPPDATA/Android/Sdk}/platform-tools/adb"
SKILL="$(cygpath -w "$HOME/Agent-Skills/android-agent-skill/scripts/android.ps1" 2>/dev/null || echo "$HOME/Agent-Skills/android-agent-skill/scripts/android.ps1")"
restart_emulator() {
  timeout 20 "$ADB" -s emulator-5554 emu kill >/dev/null 2>&1
  for _ in $(seq 1 30); do
    [ "$(powershell -NoProfile -Command "(Get-Process -Name 'qemu-system*' -ErrorAction SilentlyContinue | Measure-Object).Count")" = "0" ] && break
    sleep 2
  done
  powershell -NoProfile -Command "Get-Process -Name 'qemu-system*' -ErrorAction SilentlyContinue | Stop-Process -Force" >/dev/null 2>&1
  powershell -NoProfile -ExecutionPolicy Bypass -File "$SKILL" avd start -Name jev_playstore_36 | tail -1
  sleep 45
}
chrome_version() {
  "$ADB" -s emulator-5554 shell dumpsys package com.android.chrome | sed -n 's/.*versionName=\([0-9]*\).*/\1/p' | head -1
}
for k in $REPS; do
  for config in "${CONFIGS[@]}"; do
    set -- $config
    [ "${RESTART:-0}" = "1" ] && restart_emulator
    CHROME="${CHROME:-$(chrome_version)}"
    name="$DATE-emulador-chrome$CHROME-$1-$2-$3${SUFFIX:-}-r$k"
    node "$HERE/run-android.mjs" --result "$name" --timeout 1200 --flags "${FLAGS:-}" \
      --path "/index.html?engine=$1&variant=$2&model=$3${EXTRA:-}&name=$name" | tail -1
  done
done
